// sheetASCII keeps drawn and reported labels identical: one '?' replaces
// every rune the built-in face cannot draw.
func sheetASCII(text string) string {
	out := make([]byte, 0, len(text))
	for _, r := range text {
		if r < 32 || r > 126 {
			r = '?'
		}
		out = append(out, byte(r))
	}
	return string(out)
}

// drawSheetText draws printable ASCII with its top-left corner at x, y. Each
// glyph dot becomes a scale x scale block; dots outside the image are skipped.
func drawSheetText(img *image.RGBA, x, y, scale int, text string, red, green, blue byte) {
	bounds := img.Bounds()
	for i := 0; i < len(text); i++ {
		ch := text[i]
		if ch < 32 || ch > 126 {
			ch = '?'
		}
		glyph := sheetGlyphs[ch-32]
		for column, bits := range glyph {
			for row := 0; row < sheetGlyphHeight; row++ {
				if bits>>row&1 == 0 {
					continue
				}
				left := x + (i*sheetGlyphAdvance+column)*scale
				top := y + row*scale
				for dy := 0; dy < scale; dy++ {
					py := top + dy
					if py < bounds.Min.Y || py >= bounds.Max.Y {
						continue
					}
					for dx := 0; dx < scale; dx++ {
						px := left + dx
						if px < bounds.Min.X || px >= bounds.Max.X {
							continue
						}
						at := img.PixOffset(px, py)
						img.Pix[at], img.Pix[at+1], img.Pix[at+2], img.Pix[at+3] = red, green, blue, 0xFF
					}
				}
			}
		}
	}
}
